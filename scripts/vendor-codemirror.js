// Build a classic-script CodeMirror bundle for the renderer.
//
// WHY CODEMIRROR 5 AND NOT 6, AND NOT MONACO.
//
// The renderer runs from file:// under `script-src 'self'`, and a file:// page
// cannot load ES modules at all — Chromium refuses the cross-origin request.
// So whatever goes in has to be a classic script that assigns a global, which
// is the same constraint that shaped scripts/vendor-hljs.js.
//
//   • Monaco is 2-5 MB and is built for a full-window IDE. For one message box
//     it is the wrong size by an order of magnitude.
//   • CodeMirror 6 is ESM-only across a dozen packages and reaches its nested
//     languages through dynamic import(). Using it here would mean adding a
//     bundler to the toolchain and then hand-wiring around those imports —
//     more moving parts in the build than the editor saves in the app.
//   • CodeMirror 5 ships UMD files that fall back to a global when there is no
//     module system. They concatenate into one script with no build step, which
//     is exactly the shape this project already vendors things in.
//
// The MODE LIST is derived from the languages the composer offers, so the two
// cannot drift: a language in the menu whose mode was never bundled would
// highlight as plain text with nothing to say why.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'renderer', 'vendor');
const PKG_DIR = path.join(ROOT, 'node_modules', 'codemirror');

// Every mode file the composer's language list can reach, plus the ones the
// markdown mode itself leans on (it hands HTML blocks to xml, and php pulls in
// most of the web set).
const MODES = [
    'xml/xml',
    'markdown/markdown',
    'javascript/javascript',
    'css/css',
    'htmlmixed/htmlmixed',
    'clike/clike',
    'python/python',
    'go/go',
    'rust/rust',
    'ruby/ruby',
    'php/php',
    'swift/swift',
    'lua/lua',
    'perl/perl',
    'r/r',
    'vb/vb',
    'sql/sql',
    'yaml/yaml',
    'toml/toml',
    'properties/properties',
    'shell/shell',
    'diff/diff',
    'dockerfile/dockerfile',
    'powershell/powershell'
];

// Placeholder is what lets the box keep saying "Message #general" when empty.
const ADDONS = [
    'display/placeholder',
    'edit/closebrackets',
    'selection/active-line'
];

function main() {
    fs.mkdirSync(OUT_DIR, { recursive: true });

    if (!fs.existsSync(path.join(PKG_DIR, 'package.json'))) {
        console.warn('[vendor] codemirror not installed yet — skipping.');
        return;
    }
    const version = JSON.parse(fs.readFileSync(path.join(PKG_DIR, 'package.json'), 'utf8')).version;

    const parts = [];
    parts.push('// CodeMirror ' + version + ' — core + ' + MODES.length + ' modes + ' +
        ADDONS.length + ' addons, concatenated for a file:// renderer.');
    parts.push('// Generated by scripts/vendor-codemirror.js. Do not edit.');

    const read = (rel) => {
        const file = path.join(PKG_DIR, rel);
        if (!fs.existsSync(file)) throw new Error('vendor-codemirror: missing ' + rel);
        return fs.readFileSync(file, 'utf8');
    };

    // Core first: every mode's UMD wrapper looks for the global it defines.
    parts.push(read('lib/codemirror.js'));
    // …then the mode helpers some modes are BUILT ON. dockerfile and powershell
    // are defined through defineSimpleMode, which does not exist until this is
    // in — and a mode that fails to define takes the whole script down with it.
    parts.push(read('addon/mode/simple.js'));
    for (const m of MODES) parts.push(read('mode/' + m + '.js'));
    for (const a of ADDONS) parts.push(read('addon/' + a + '.js'));

    const js = parts.join('\n;\n');
    fs.writeFileSync(path.join(OUT_DIR, 'codemirror.js'), js);

    // The editor's own stylesheet. The app's theme is layered over it in
    // styles.css rather than edited here, so this file stays replaceable.
    const css = [
        read('lib/codemirror.css'),
        read('addon/display/placeholder.js') ? '' : ''
    ].join('\n');
    fs.writeFileSync(path.join(OUT_DIR, 'codemirror.css'), css);

    const kb = Math.round(js.length / 1024);
    console.log('[vendor] codemirror ' + version + ' -> codemirror.js (' +
        MODES.length + ' modes, ' + kb + ' KB) + codemirror.css');
}

main();
